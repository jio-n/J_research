def build_priorities(cards,defs):
 by={c['card_id']:c for c in cards};names={d['category_id']:d['category'] for d in defs};rows=[]
 for cat,selections in SELECTIONS.items():
  for order,(ids,tier,reason,question) in enumerate(selections,1):
   cs=[by[i] for i in ids.split(',')]
   assert len({c['company'] for c in cs})==1
   assert any(cat in [t['category_id'] for t in c['categories']] for c in cs),(cat,ids)
   join=lambda key:'\n'.join(dict.fromkeys(c[key] for c in cs))
   row=dict(priority_id=f'{cat}-P{order:02}',category_id=cat,category=names[cat],category_order=order,priority=tier,company=cs[0]['company'],booths_2026=list(dict.fromkeys(b for c in cs for b in c['booths_2026'])),exhibits=join('item'),why_visit=reason,baseline_2024=join('baseline_2024'),observation_2026=join('observation_2026'),delta_type=join('delta_type'),comparison_interpretation=join('delta_interpretation'),on_site_check=question,exhibition_status=join('exhibition_status'),product_stage=join('product_stage'),card_ids=[c['card_id'] for c in cs],evidence_ids=list(dict.fromkeys(e for c in cs for e in c['evidence_ids'])),selection_basis='調査者の訪問順案。具体タスク・年度比較・方式の比較価値・未確認点の解消を重視。製品性能や採用率の順位ではない。',checked_date='2026-10-16')
   for key in ['ai_scope','ai_judgment','execution','human_preparation','human_approval','human_exception','limits','source_status']:
    row[key]='\n'.join(dict.fromkeys(c['deepening'][key] for c in cs))
   rows.append(row)
 return rows
